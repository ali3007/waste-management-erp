          'complaint_time', 'location_address', 'latitude', 'longitude'] as $k) {
    $form[$k] = old($k, (string)($complaint[$k] ?? ''));
}

$pageTitle = 'Edit ' . $complaint['complaint_number'];
$layout = 'app';
$extraScripts = ['complaints.js'];

require INCLUDES_PATH . '/header.php';
?>

