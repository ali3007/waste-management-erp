/**
 * Complaints — one definition of "which complaints match these filters",
 * shared by the dashboard (charts + listing), the reports page, the
 * exports and the PDF list, so a screen and its download can never
 * disagree. The signed-in user's UC scope is ALWAYS added here, in the
 * SQL, so no filter value can widen what a user is allowed to see.
 *
 * Dates filter on the complaint's own date (the day it was received), with
 * no limit on how far back — any historical day or range works, together
 * with every other filter.
 */
declare(strict_types=1);
defined('SWMS') || exit('Direct access is not allowed.');

const CMP_FILTER_KEYS = [
    'q', 'number', 'complainant', 'phone', 'range', 'date_from', 'date_to', 'region', 'district', 'tehsil', 'uc', 'beat',
    'source', 'type', 'priority', 'status', 'supervisor', 'monitor', 'sla', 'deleted',
];

/** Resolve a quick-range keyword to [from, to] (Y-m-d), or null for "custom". */
function cmp_quick_range(string $range): ?array
{
    $today = new DateTimeImmutable('today');
    return match ($range) {
        'today'      => [$today->format('Y-m-d'), $today->format('Y-m-d')],
        'week'       => [$today->modify('monday this week')->format('Y-m-d'), $today->modify('sunday this week')->format('Y-m-d')],
        'month'      => [$today->modify('first day of this month')->format('Y-m-d'), $today->modify('last day of this month')->format('Y-m-d')],
        'last_month' => [$today->modify('first day of last month')->format('Y-m-d'), $today->modify('last day of last month')->format('Y-m-d')],
        default      => null,
    };
}

/** Read + sanitise filters from a request array. */
function cmp_read_filters(array $src): array
{
    $text = static fn(string $k): string => isset($src[$k]) && is_string($src[$k]) ? trim($src[$k]) : '';
    $int = static fn(string $k): int => max(0, (int)$text($k));

    $f = [
        'q' => Security::cleanText($text('q'), 120), 'number' => Security::cleanText($text('number'), 40),
        'complainant' => Security::cleanText($text('complainant'), 120), 'phone' => Security::cleanText($text('phone'), 30),
        'range' => in_array($text('range'), ['today', 'week', 'month', 'last_month', 'custom'], true) ? $text('range') : '',
        'date_from' => '', 'date_to' => '',
        'region' => $int('region'), 'district' => $int('district'), 'tehsil' => $int('tehsil'), 'uc' => $int('uc'), 'beat' => $int('beat'),
        'source' => $int('source'), 'type' => $int('type'), 'priority' => $int('priority'),
        'status' => array_key_exists($text('status'), cmp_statuses()) ? $text('status') : '',
        'supervisor' => $int('supervisor'), 'monitor' => $int('monitor'),
        'sla' => in_array($text('sla'), ['within', 'nearing', 'breached'], true) ? $text('sla') : '',
        'deleted' => $text('deleted') === '1' ? '1' : '',
    ];

    $quick = $f['range'] !== '' ? cmp_quick_range($f['range']) : null;
    if ($quick !== null) {
        [$f['date_from'], $f['date_to']] = $quick;
    } else {
        $from = cmp_parse_date($text('date_from'));
        $to = cmp_parse_date($text('date_to'));
        $f['date_from'] = $from ?? '';
        $f['date_to'] = $to ?? '';
        if ($f['date_from'] !== '' && $f['date_to'] !== '' && $f['date_from'] > $f['date_to']) {
            [$f['date_from'], $f['date_to']] = [$f['date_to'], $f['date_from']];
        }
        if ($f['range'] === 'custom' && $f['date_from'] === '' && $f['date_to'] === '') {
            $f['range'] = '';
        }
    }
    return $f;
}

function cmp_active_filters(array $f): array
{
    return array_filter($f, static fn($v) => $v !== '' && $v !== 0);
}

function cmp_filter_query(array $f, array $extra = []): string
{
    $params = array_merge(cmp_active_filters($f), $extra);
    $params = array_filter($params, static fn($v) => $v !== '' && $v !== null && $v !== 0);
    return $params ? '?' . http_build_query($params) : '';
}

/**
 * SQL for "SLA state = X". $now is generated by cmp_now() and embedded as
 * a literal (it can only ever be a date() string, never user input).
 */
function cmp_sla_sql(string $state, string $alias = 'c', ?string $now = null): string
{
    $now = "'" . ($now ?? cmp_now()) . "'";
    $c = $alias;
    return match ($state) {
        'breached' => "({$c}.sla_due_at IS NOT NULL AND {$c}.status <> 'rejected' AND (({$c}.status = 'resolved' AND {$c}.resolved_at > {$c}.sla_due_at) OR ({$c}.status <> 'resolved' AND {$now} > {$c}.sla_due_at)))",
        'nearing'  => "({$c}.sla_due_at IS NOT NULL AND {$c}.status NOT IN ('resolved','rejected') AND {$now} >= {$c}.sla_warn_at AND {$now} <= {$c}.sla_due_at)",
        'within'   => "({$c}.sla_due_at IS NOT NULL AND {$c}.status <> 'rejected' AND (({$c}.status = 'resolved' AND {$c}.resolved_at <= {$c}.sla_due_at) OR ({$c}.status <> 'resolved' AND {$now} < {$c}.sla_warn_at)))",
        default    => '1 = 1',
    };
}

/**
 * WHERE clause + parameters for a filter set (alias `c`). Always
 * includes the user's UC scope and the soft-delete rule.
 *
 * @return array{0:string,1:array}
 */
function cmp_filter_sql(array $f, string $c = 'c'): array
{
    $where = [];
    $p = [];

    /* Soft delete: normal listings never show deleted complaints; users
       who may restore can switch to "deleted only". */
    $where[] = ($f['deleted'] === '1' && can('complaint.restore')) ? "{$c}.deleted_at IS NOT NULL" : "{$c}.deleted_at IS NULL";

    $scope = cmp_scope_sql($c);
    if ($scope !== '') {
        $where[] = $scope;
    }

    $like = static fn(string $v): string => '%' . str_replace(['\\', '%', '_'], ['\\\\', '\\%', '\\_'], $v) . '%';

    if ($f['q'] !== '') {
        $l = $like($f['q']);
        $or = [
            "{$c}.complaint_number LIKE :q1", "{$c}.complainant_name LIKE :q2", "{$c}.phone LIKE :q3",
            "{$c}.complainant_address LIKE :q4", "{$c}.location_address LIKE :q5", "{$c}.description LIKE :q6",
        ];
        $p += ['q1' => $l, 'q2' => $l, 'q3' => $l, 'q4' => $l, 'q5' => $l, 'q6' => $l];
        $digits = preg_replace('/\D+/', '', $f['q']) ?? '';
        if (strlen($digits) >= 5) {
            $or[] = "REPLACE(REPLACE(REPLACE({$c}.phone, '-', ''), ' ', ''), '+', '') LIKE :q7";
            $p['q7'] = '%' . $digits . '%';
        }
        $where[] = '(' . implode(' OR ', $or) . ')';
    }
    if ($f['number'] !== '') {
        $where[] = "{$c}.complaint_number LIKE :number";
        $p['number'] = $like($f['number']);
    }
    if ($f['complainant'] !== '') {
        $where[] = "{$c}.complainant_name LIKE :complainant";
        $p['complainant'] = $like($f['complainant']);
    }
    if ($f['phone'] !== '') {
        $digits = preg_replace('/\D+/', '', $f['phone']) ?? '';
        $where[] = "(REPLACE(REPLACE(REPLACE({$c}.phone, '-', ''), ' ', ''), '+', '') LIKE :phone1 OR {$c}.phone LIKE :phone2)";
        $p['phone1'] = '%' . ($digits !== '' ? $digits : $f['phone']) . '%';
        $p['phone2'] = $like($f['phone']);
    }
    if ($f['date_from'] !== '') {
        $where[] = "{$c}.complaint_date >= :date_from";
        $p['date_from'] = $f['date_from'];
    }
    if ($f['date_to'] !== '') {
        $where[] = "{$c}.complaint_date <= :date_to";
        $p['date_to'] = $f['date_to'];
    }
    foreach (['region' => 'region_id', 'district' => 'district_id', 'tehsil' => 'tehsil_id', 'uc' => 'uc_id', 'beat' => 'beat_id',
              'source' => 'source_id', 'type' => 'type_id', 'priority' => 'priority_id'] as $key => $col) {
        if ($f[$key] > 0) {
            $where[] = "{$c}.{$col} = :f_{$key}";
            $p['f_' . $key] = $f[$key];
        }
    }
    if ($f['status'] !== '') {
        $where[] = "{$c}.status = :f_status";
        $p['f_status'] = $f['status'];
    }
    foreach (['supervisor' => $f['supervisor'], 'monitor' => $f['monitor']] as $key => $empId) {
        if ($empId > 0) {
            $where[] = "EXISTS (SELECT 1 FROM employee_assignments ea_{$key} WHERE ea_{$key}.uc_id = {$c}.uc_id AND ea_{$key}.unassigned_at IS NULL AND ea_{$key}.employee_id = :f_{$key})";
            $p['f_' . $key] = $empId;
        }
    }
    if ($f['sla'] !== '') {
        $where[] = cmp_sla_sql($f['sla'], $c);
    }
    return [implode(' AND ', $where), $p];
}

/** Columns + joins the list/report/export queries share. */
function cmp_list_select(): string
{
    return "SELECT c.id, c.complaint_number, c.complainant_name, c.complainant_address, c.phone, c.description, c.complaint_date, c.complaint_time,
                   c.location_address, c.latitude, c.longitude, c.status, c.created_at, c.assigned_at, c.resolved_at, c.deleted_at,
                   c.sla_start_at, c.sla_warn_at, c.sla_due_at, c.uc_id,
                   s.name AS source_name, ty.name AS type_name, p.name AS priority_name, p.color AS priority_color,
                   r.name AS region_name, d.name AS district_name, t.name AS tehsil_name, u.name AS uc_name, b.name AS beat_name,
                   (SELECT COUNT(*) FROM complaint_evidence ev WHERE ev.complaint_id = c.id AND ev.kind = 'before') AS before_count,
                   (SELECT COUNT(*) FROM complaint_evidence ev2 WHERE ev2.complaint_id = c.id AND ev2.kind = 'after') AS after_count
              FROM complaints c
              JOIN complaint_sources s ON s.id = c.source_id
              JOIN complaint_types ty ON ty.id = c.type_id
              JOIN complaint_priorities p ON p.id = c.priority_id
              JOIN regions r ON r.id = c.region_id
              JOIN districts d ON d.id = c.district_id
              JOIN tehsils t ON t.id = c.tehsil_id
              JOIN ucs u ON u.id = c.uc_id
              LEFT JOIN beats b ON b.id = c.beat_id";
}

/** A page of complaints for a filter set. @return array{rows:array,total:int} */
function cmp_list(array $f, int $page, int $perPage): array
{
    [$where, $params] = cmp_filter_sql($f);
    $total = (int)Database::fetchValue("SELECT COUNT(*) FROM complaints c WHERE {$where}", $params);
    $page = max(1, min($page, max(1, (int)ceil($total / $perPage))));
    $offset = ($page - 1) * $perPage;
    $rows = Database::fetchAll(
        cmp_list_select() . " WHERE {$where} ORDER BY c.complaint_date DESC, c.id DESC LIMIT {$perPage} OFFSET {$offset}",
        $params
    );
    return ['rows' => $rows, 'total' => $total, 'page' => $page];
}

