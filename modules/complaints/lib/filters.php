/**
 * Everything the dashboard shows, in one structure, from live data and the
 * same filters/scope as the listing — so all charts update together.
 *
 * @return array<string,mixed>
 */
function cmp_dashboard_data(array $f, string $group = 'auto'): array
{
    [$where, $params] = cmp_filter_sql($f);
    $now = cmp_now();

    $row = Database::fetch(
        "SELECT COUNT(*) AS total,
                COALESCE(SUM(c.status = 'new'), 0) AS st_new, COALESCE(SUM(c.status = 'assigned'), 0) AS st_assigned,
                COALESCE(SUM(c.status = 'in_progress'), 0) AS st_in_progress, COALESCE(SUM(c.status = 'ready'), 0) AS st_ready,
                COALESCE(SUM(c.status = 'resolved'), 0) AS st_resolved, COALESCE(SUM(c.status = 'reopened'), 0) AS st_reopened,
                COALESCE(SUM(c.status = 'rejected'), 0) AS st_rejected,
                COALESCE(SUM(" . cmp_sla_sql('within', 'c', $now) . "), 0) AS sla_within,
                COALESCE(SUM(" . cmp_sla_sql('nearing', 'c', $now) . "), 0) AS sla_nearing,
                COALESCE(SUM(" . cmp_sla_sql('breached', 'c', $now) . "), 0) AS sla_breached
           FROM complaints c WHERE {$where}",
        $params
    ) ?: [];

    $cards = ['total' => (int)($row['total'] ?? 0), 'status' => [], 'sla' => [
        'within' => (int)($row['sla_within'] ?? 0), 'nearing' => (int)($row['sla_nearing'] ?? 0), 'breached' => (int)($row['sla_breached'] ?? 0),
    ]];
    foreach (cmp_statuses() as $slug => $st) {
        $cards['status'][] = ['slug' => $slug, 'label' => $st['label'], 'color' => $st['color'], 'count' => (int)($row['st_' . $slug] ?? 0)];
    }

    /* ---- Trend: daily / weekly / monthly over the selected range ---- */
    $bounds = Database::fetch("SELECT MIN(c.complaint_date) AS d1, MAX(c.complaint_date) AS d2 FROM complaints c WHERE {$where}", $params) ?: [];
    $from = $f['date_from'] !== '' ? $f['date_from'] : ($bounds['d1'] ?? null);
    $to = $f['date_to'] !== '' ? $f['date_to'] : ($bounds['d2'] ?? null);
    $trend = ['group' => 'day', 'labels' => [], 'keys' => [], 'values' => [], 'from' => $from, 'to' => $to, 'note' => ''];

    if ($from !== null && $to !== null) {
        $days = (int)((strtotime($to) - strtotime($from)) / 86400) + 1;
        if (!in_array($group, ['day', 'week', 'month'], true)) {
            $group = $days <= 62 ? 'day' : ($days <= 366 ? 'week' : 'month');
        }
        if ($group === 'day' && $days > 400) {
            $group = 'week';
            $trend['note'] = 'Range is long, so the trend is shown weekly.';
        }
        if ($group === 'week' && $days > 3000) {
            $group = 'month';
            $trend['note'] = 'Range is very long, so the trend is shown monthly.';
        }
        $trend['group'] = $group;

        $expr = match ($group) {
            'day'   => 'c.complaint_date',
            'week'  => 'DATE_SUB(c.complaint_date, INTERVAL WEEKDAY(c.complaint_date) DAY)',
            default => "DATE_FORMAT(c.complaint_date, '%Y-%m-01')",
        };
        $found = [];
        foreach (Database::fetchAll(
            "SELECT {$expr} AS bucket, COUNT(*) AS cnt FROM complaints c WHERE {$where} AND c.complaint_date BETWEEN :tf AND :tt GROUP BY bucket",
            $params + ['tf' => $from, 'tt' => $to]
        ) as $r) {
            $found[(string)$r['bucket']] = (int)$r['cnt'];
        }

        /* Fill gaps so empty days/weeks/months show as zero, not as missing. */
        $cursor = new DateTimeImmutable($from);
        $end = new DateTimeImmutable($to);
        if ($group === 'week') {
            $cursor = $cursor->modify('monday this week');
        } elseif ($group === 'month') {
            $cursor = $cursor->modify('first day of this month');
        }
        $guard = 0;
        while ($cursor <= $end && $guard++ < 1500) {
            $key = $cursor->format('Y-m-d');
            $trend['labels'][] = match ($group) {
                'day' => $cursor->format('d M Y'), 'week' => 'Week of ' . $cursor->format('d M Y'), default => $cursor->format('M Y'),
            };
            $trend['keys'][] = $key;
            $trend['values'][] = $found[$key] ?? 0;
            $cursor = $group === 'day' ? $cursor->modify('+1 day') : ($group === 'week' ? $cursor->modify('+7 days') : $cursor->modify('+1 month'));
        }
    }

    /* ---- UC-wise ---- */
    $ucRows = Database::fetchAll(
        "SELECT u.id, u.name, t.name AS tehsil_name, COUNT(*) AS cnt,
                SUM(c.status IN ('new','assigned')) AS pending, SUM(c.status IN ('in_progress','ready')) AS progress,
                SUM(c.status = 'resolved') AS resolved, SUM(c.status = 'reopened') AS reopened, SUM(c.status = 'rejected') AS rejected
           FROM complaints c JOIN ucs u ON u.id = c.uc_id JOIN tehsils t ON t.id = u.tehsil_id
          WHERE {$where} GROUP BY u.id, u.name, t.name ORDER BY cnt DESC, u.name ASC",
        $params
    );
    $ucTotal = count($ucRows);
    $ucTop = array_slice($ucRows, 0, 25);
    $byUc = array_map(static fn($r) => ['id' => (int)$r['id'], 'label' => (string)$r['name'], 'sub' => (string)$r['tehsil_name'], 'value' => (int)$r['cnt']], $ucTop);
    $ucStatus = array_map(static fn($r) => [
        'id' => (int)$r['id'], 'label' => (string)$r['name'], 'pending' => (int)$r['pending'], 'progress' => (int)$r['progress'],
        'resolved' => (int)$r['resolved'], 'reopened' => (int)$r['reopened'], 'rejected' => (int)$r['rejected'],
    ], array_slice($ucRows, 0, 15));

    $dim = static function (string $table, string $col) use ($where, $params): array {
        return Database::fetchAll(
            "SELECT x.id, x.name, COUNT(*) AS cnt FROM complaints c JOIN {$table} x ON x.id = c.{$col} WHERE {$where} GROUP BY x.id, x.name ORDER BY cnt DESC, x.name ASC LIMIT 30",
            $params
        );
    };
    $map = static fn(array $rows): array => array_map(static fn($r) => ['id' => (int)$r['id'], 'label' => (string)$r['name'], 'value' => (int)$r['cnt']], $rows);

    return [
        'cards' => $cards,
        'trend' => $trend,
        'by_uc' => $byUc, 'uc_total' => $ucTotal,
        'by_type' => $map($dim('complaint_types', 'type_id')),
        'by_source' => $map($dim('complaint_sources', 'source_id')),
        'by_status' => $cards['status'],
        'uc_status' => $ucStatus,
    ];
}
